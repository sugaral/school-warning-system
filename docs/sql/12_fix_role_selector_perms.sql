-- Role IDs:
--   head_teacher   = 1909000000000000001
--   teacher        = 1909000000000000002
--   teaching_admin = 1909000000000000004
--   vice_dean      = 1909000000000000005

INSERT INTO `SYS_RELATION` (`ID`, `OBJECT_ID`, `TARGET_ID`, `CATEGORY`, `EXT_JSON`)
SELECT v.ID, v.OBJECT_ID, v.TARGET_ID, 'SYS_ROLE_HAS_PERMISSION',
       CONCAT('{"apiUrl":"', v.TARGET_ID, '","scopeCategory":"SCOPE_ORG_CHILD","scopeDefineOrgIdList":[]}')
FROM (
    SELECT '1912000000000000001' AS ID, '1909000000000000002' AS OBJECT_ID, '/biz/clazz/orgTreeSelector' AS TARGET_ID
    UNION ALL SELECT '1912000000000000002', '1909000000000000002', '/biz/clazz/userSelector'
    UNION ALL SELECT '1912000000000000003', '1909000000000000002', '/biz/calendar/orgTreeSelector'
    UNION ALL SELECT '1912000000000000004', '1909000000000000001', '/biz/calendar/orgTreeSelector'
    UNION ALL SELECT '1912000000000000005', '1909000000000000001', '/biz/clazz/userSelector'
    UNION ALL SELECT '1912000000000000006', '1909000000000000001', '/biz/course/list'
    UNION ALL SELECT '1912000000000000007', '1909000000000000001', '/biz/major/list'
    UNION ALL SELECT '1912000000000000008', '1909000000000000001', '/biz/warningrule/orgTreeSelector'
    UNION ALL SELECT '1912000000000000009', '1909000000000000004', '/biz/warningrule/orgTreeSelector'
    UNION ALL SELECT '1912000000000000010', '1909000000000000005', '/biz/calendar/orgTreeSelector'
    UNION ALL SELECT '1912000000000000011', '1909000000000000005', '/biz/warningrule/orgTreeSelector'
) v
WHERE NOT EXISTS (
    SELECT 1 FROM `SYS_RELATION` r
    WHERE r.OBJECT_ID = v.OBJECT_ID
      AND r.TARGET_ID = v.TARGET_ID
      AND r.CATEGORY = 'SYS_ROLE_HAS_PERMISSION'
);
