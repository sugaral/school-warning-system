export const CHANGE_REQUEST_STATUS = {
  SUBMITTED: 'submitted',
  PENDING_HEAD: 'pending_head',
  PENDING_DEAN: 'pending_dean',
  APPROVED: 'approved',
  REJECTED: 'rejected',
} as const;

export const LEGACY_CHANGE_REQUEST_STATUS = {
  PENDING_HEAD: 'pending_head_teacher',
  PENDING_DEAN: 'pending_vice_dean',
} as const;

export const CHANGE_REQUEST_PENDING_HEAD_STATUSES = [
  CHANGE_REQUEST_STATUS.PENDING_HEAD,
  LEGACY_CHANGE_REQUEST_STATUS.PENDING_HEAD,
] as const;

export const CHANGE_REQUEST_PENDING_DEAN_STATUSES = [
  CHANGE_REQUEST_STATUS.PENDING_DEAN,
  LEGACY_CHANGE_REQUEST_STATUS.PENDING_DEAN,
] as const;

export const CHANGE_REQUEST_OPEN_PENDING_STATUSES = [
  ...CHANGE_REQUEST_PENDING_HEAD_STATUSES,
  ...CHANGE_REQUEST_PENDING_DEAN_STATUSES,
] as const;

export const CHANGE_REQUEST_DEAN_QUEUE_STATUSES = [
  CHANGE_REQUEST_STATUS.SUBMITTED,
  ...CHANGE_REQUEST_PENDING_DEAN_STATUSES,
] as const;

export function normalizeChangeRequestStatus(status?: string | null) {
  if (status === LEGACY_CHANGE_REQUEST_STATUS.PENDING_HEAD) {
    return CHANGE_REQUEST_STATUS.PENDING_HEAD;
  }
  if (status === LEGACY_CHANGE_REQUEST_STATUS.PENDING_DEAN) {
    return CHANGE_REQUEST_STATUS.PENDING_DEAN;
  }
  return status || '';
}
